#!/usr/bin/env node
/**
 * verify-corpus.mjs — the build gate.
 *
 * Plain Node ESM, zero dependencies, read-only except for the counts and hash it
 * writes back into data/corpus/meta.json. Safe to re-run. Every failure names the
 * file, the record and the field, so the fix is obvious rather than archaeological.
 *
 *   node scripts/verify-corpus.mjs            C1-C7, C9 (source), C10-C14
 *   node scripts/verify-corpus.mjs --built    adds C8 and C9 over emitted HTML and the résumé PDF
 *   node scripts/verify-corpus.mjs --strict    turns C11 staleness warnings into failures
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * SCAN SCOPE — read this before adding a directory
 * ─────────────────────────────────────────────────────────────────────────────
 * The numeric gate (C8) and the retraction gate (C9) run over the NEW surfaces
 * only: the emitted Next.js HTML and the hand-authored source that feeds it.
 *
 * `public/docs/**` is deliberately EXCLUDED. Those are frozen legacy pages,
 * preserved byte-for-byte because live URLs point at them from a résumé and from
 * LinkedIn, and they are full of exactly the figures this corpus retracts. Scanning
 * them would produce a build that can never go green, and a gate that can never
 * pass is a gate that gets deleted. They are covered instead by the migration's own
 * URL-and-byte-size harness, which asserts they have not changed.
 *
 * The two exceptions inside that directory are files this corpus OWNS, and they
 * are scanned:
 *   public/docs/resume_content.html   generated by scripts/gen-resume.mjs
 *   public/docs/Resume.pdf            scanned as extracted text (see C9)
 *
 * `data/corpus/**` is also excluded from the bulk C9 scan, for the obvious reason:
 * the retraction records quote the strings they forbid. Instead, C9 scans the three
 * corpus fields that are actually SPOKEN — a gap's honestAnswer, a dispute's
 * agentGuidance, and a requirement's fallback — because those reach a reader.
 */

import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
} from 'node:fs'
import { resolve, dirname, join, relative, extname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CORPUS = join(ROOT, 'data', 'corpus')
const SCHEMAS = join(CORPUS, 'schemas')

const argv = process.argv.slice(2)
const BUILT = argv.includes('--built')
const STRICT = argv.includes('--strict')
const QUIET = argv.includes('--quiet')

const failures = []
const warnings = []
const fail = (check, where, msg) => failures.push({ check, where, msg })
const warn = (check, where, msg) => warnings.push({ check, where, msg })

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))

/* ═══════════════════════════════════════════════════════════════════════════
   A small JSON Schema evaluator.
   Only the keywords this corpus actually uses, implemented honestly rather than
   approximated: type, required, additionalProperties, properties, items, enum,
   const, pattern, minLength/maxLength, minItems/maxItems, minimum/maximum,
   format:"date", and allOf with if/then. Anything unrecognised is reported rather
   than ignored, so a schema keyword that silently does nothing cannot creep in.
   ═══════════════════════════════════════════════════════════════════════════ */

const KNOWN = new Set([
  '$schema', '$id', 'title', 'description', '$defs', 'note',
  'type', 'required', 'additionalProperties', 'properties', 'items',
  'enum', 'const', 'pattern', 'minLength', 'maxLength', 'minItems', 'maxItems',
  'minimum', 'maximum', 'format', 'allOf', 'if', 'then',
])

const typeOf = (v) =>
  v === null ? 'null' : Array.isArray(v) ? 'array' : Number.isInteger(v) ? 'integer' : typeof v

function typeMatches(value, expected) {
  const actual = typeOf(value)
  const list = Array.isArray(expected) ? expected : [expected]
  return list.some((t) =>
    t === 'number' ? actual === 'number' || actual === 'integer' : t === actual
  )
}

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/

function validate(schema, value, path, out) {
  for (const key of Object.keys(schema)) {
    if (!KNOWN.has(key)) out.push(`${path}: schema uses unsupported keyword "${key}"`)
  }

  if (schema.type !== undefined && !typeMatches(value, schema.type)) {
    out.push(`${path}: expected type ${JSON.stringify(schema.type)}, got ${typeOf(value)}`)
    return
  }
  if (schema.enum && !schema.enum.includes(value)) {
    out.push(`${path}: ${JSON.stringify(value)} is not one of ${JSON.stringify(schema.enum)}`)
  }
  if (schema.const !== undefined && value !== schema.const) {
    out.push(`${path}: expected constant ${JSON.stringify(schema.const)}, got ${JSON.stringify(value)}`)
  }

  if (typeof value === 'string') {
    if (schema.pattern && !new RegExp(schema.pattern).test(value)) {
      out.push(`${path}: ${JSON.stringify(value.slice(0, 60))} does not match /${schema.pattern}/`)
    }
    if (schema.minLength !== undefined && value.length < schema.minLength) {
      out.push(`${path}: length ${value.length} is below minLength ${schema.minLength}`)
    }
    if (schema.maxLength !== undefined && value.length > schema.maxLength) {
      out.push(`${path}: length ${value.length} exceeds maxLength ${schema.maxLength}`)
    }
    if (schema.format === 'date' && !DATE_RE.test(value)) {
      out.push(`${path}: ${JSON.stringify(value)} is not an ISO date (YYYY-MM-DD)`)
    }
  }

  if (typeof value === 'number') {
    if (schema.minimum !== undefined && value < schema.minimum) {
      out.push(`${path}: ${value} is below minimum ${schema.minimum}`)
    }
    if (schema.maximum !== undefined && value > schema.maximum) {
      out.push(`${path}: ${value} exceeds maximum ${schema.maximum}`)
    }
  }

  if (Array.isArray(value)) {
    if (schema.minItems !== undefined && value.length < schema.minItems) {
      out.push(`${path}: ${value.length} item(s), minItems is ${schema.minItems}`)
    }
    if (schema.maxItems !== undefined && value.length > schema.maxItems) {
      out.push(`${path}: ${value.length} item(s), maxItems is ${schema.maxItems}`)
    }
    if (schema.items) {
      value.forEach((item, i) => validate(schema.items, item, `${path}/${i}`, out))
    }
  }

  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const key of schema.required ?? []) {
      if (!(key in value)) out.push(`${path}: missing required property "${key}"`)
    }
    if (schema.additionalProperties === false && schema.properties) {
      for (const key of Object.keys(value)) {
        if (!(key in schema.properties)) out.push(`${path}: unexpected property "${key}"`)
      }
    }
    for (const [key, sub] of Object.entries(schema.properties ?? {})) {
      if (key in value) validate(sub, value[key], `${path}/${key}`, out)
    }
  }

  for (const sub of schema.allOf ?? []) {
    if (sub.if) {
      const probe = []
      validate(sub.if, value, path, probe)
      if (probe.length === 0 && sub.then) validate(sub.then, value, path, out)
    } else {
      validate(sub, value, path, out)
    }
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   Load everything.
   ═══════════════════════════════════════════════════════════════════════════ */

const FILES = {
  claims: 'claims.json',
  sources: 'sources.json',
  orgs: 'orgs.json',
  people: 'people.json',
  roles: 'roles.json',
  artifacts: 'artifacts.json',
  concepts: 'concepts.json',
  skills: 'skills.json',
  gaps: 'gaps.json',
  disputes: 'disputes.json',
  retractions: 'retractions.json',
  roleProfiles: 'role-profiles.json',
  allowedNumbers: 'allowed-non-claim-numbers.json',
  meta: 'meta.json',
}

const data = {}
for (const [key, file] of Object.entries(FILES)) {
  const p = join(CORPUS, file)
  if (!existsSync(p)) {
    fail('C1', file, 'file is missing from data/corpus/')
    continue
  }
  try {
    data[key] = readJson(p)
  } catch (err) {
    fail('C1', file, `is not valid JSON: ${err.message}`)
  }
}

const snapshotPath = join(CORPUS, 'fischer-snapshot.json')
const snapshot = existsSync(snapshotPath) ? readJson(snapshotPath) : null

if (failures.length) {
  report()
  process.exit(1)
}

const claimById = new Map(data.claims.map((c) => [c.id, c]))
const byId = {
  src: new Set(data.sources.map((s) => s.id)),
  org: new Set(data.orgs.map((o) => o.id)),
  per: new Set(data.people.map((p) => p.id)),
  rol: new Set(data.roles.map((r) => r.id)),
  art: new Set(data.artifacts.map((a) => a.id)),
  cpt: new Set(data.concepts.map((c) => c.id)),
  skl: new Set(data.skills.map((s) => s.id)),
  gap: new Set(data.gaps.map((g) => g.id)),
  dsp: new Set(data.disputes.map((d) => d.id)),
  ret: new Set(data.retractions.map((r) => r.id)),
  clm: new Set(data.claims.map((c) => c.id)),
  rp: new Set(data.roleProfiles.map((p) => p.id)),
}

/* ═══════════════════════════════════════════════════════════════════════════
   C1 — schema validation
   ═══════════════════════════════════════════════════════════════════════════ */

{
  const claimSchema = readJson(join(SCHEMAS, 'claim.schema.json'))
  const sourceSchema = readJson(join(SCHEMAS, 'source.schema.json'))
  const retractionSchema = readJson(join(SCHEMAS, 'retraction.schema.json'))
  const misc = readJson(join(SCHEMAS, 'misc.schema.json'))

  const pairs = [
    ['claims.json', claimSchema, data.claims],
    ['sources.json', sourceSchema, data.sources],
    ['retractions.json', retractionSchema, data.retractions],
    ['orgs.json', misc.$defs.org, data.orgs],
    ['people.json', misc.$defs.person, data.people],
    ['roles.json', misc.$defs.role, data.roles],
    ['artifacts.json', misc.$defs.artifact, data.artifacts],
    ['concepts.json', misc.$defs.concept, data.concepts],
    ['skills.json', misc.$defs.skill, data.skills],
    ['gaps.json', misc.$defs.gap, data.gaps],
    ['disputes.json', misc.$defs.dispute, data.disputes],
    ['role-profiles.json', misc.$defs.roleProfile, data.roleProfiles],
    ['allowed-non-claim-numbers.json', misc.$defs.allowedNumber, data.allowedNumbers],
    ['meta.json', misc.$defs.meta, data.meta],
  ]
  if (snapshot) pairs.push(['fischer-snapshot.json', misc.$defs.fischerSnapshot, snapshot])

  for (const [file, schema, value] of pairs) {
    const out = []
    validate(schema, value, '#', out)
    for (const message of out) fail('C1', file, message)
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C2 — status invariants
   ═══════════════════════════════════════════════════════════════════════════ */

for (const c of data.claims) {
  if (c.status === 'disputed') {
    if (c.asserted) fail('C2', `claims.json#${c.id}`, 'status is "disputed" but asserted is true')
    if (!c.disputeId) fail('C2', `claims.json#${c.id}`, 'status is "disputed" with no disputeId')
    if (c.surfaces.some((s) => s !== 'internal')) {
      fail('C2', `claims.json#${c.id}`, `disputed claim is licensed for ${c.surfaces.join(', ')} — only "internal" is allowed`)
    }
  }
  if (c.kind === 'metric' && !c.value) {
    fail('C2', `claims.json#${c.id}`, 'kind is "metric" with no value block')
  }
  if (c.kind !== 'metric' && c.value) {
    fail('C2', `claims.json#${c.id}`, `kind is "${c.kind}" but carries a value block — only metrics may`)
  }
}

// Every id namespace is unique across the whole corpus.
{
  const seen = new Map()
  const all = [
    ...data.claims, ...data.sources, ...data.orgs, ...data.people, ...data.roles,
    ...data.artifacts, ...data.concepts, ...data.skills, ...data.gaps,
    ...data.disputes, ...data.retractions, ...data.roleProfiles,
  ]
  for (const rec of all) {
    if (seen.has(rec.id)) fail('C2', rec.id, 'duplicate id in the corpus')
    seen.set(rec.id, true)
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C3 — referential integrity, in both directions
   ═══════════════════════════════════════════════════════════════════════════ */

function refs(where, ids, prefix, field) {
  for (const id of ids ?? []) {
    if (!byId[prefix].has(id)) fail('C3', where, `${field} points at "${id}", which does not exist`)
  }
}

for (const c of data.claims) {
  const where = `claims.json#${c.id}`
  const subjectPrefix = c.subject.split(':')[0]
  if (!byId[subjectPrefix] || !byId[subjectPrefix].has(c.subject)) {
    fail('C3', where, `subject "${c.subject}" does not resolve`)
  }
  refs(where, c.sources, 'src', 'sources')
  refs(where, c.concepts, 'cpt', 'concepts')
  refs(where, c.skills, 'skl', 'skills')
  refs(where, c.artifacts, 'art', 'artifacts')
  refs(where, c.caveats, 'clm', 'caveats')
  refs(where, c.derivedFrom, 'clm', 'derivedFrom')
  if (c.disputeId) refs(where, [c.disputeId], 'dsp', 'disputeId')
}

for (const s of data.skills) {
  refs(`skills.json#${s.id}`, s.groundedIn, 'clm', 'groundedIn')
  refs(`skills.json#${s.id}`, s.concepts, 'cpt', 'concepts')
}
for (const g of data.gaps) {
  refs(`gaps.json#${g.id}`, g.concepts, 'cpt', 'concepts')
  refs(`gaps.json#${g.id}`, g.nearestEvidence, 'clm', 'nearestEvidence')
}
for (const d of data.disputes) {
  refs(`disputes.json#${d.id}`, d.positions.map((p) => p.sourceId), 'src', 'positions[].sourceId')
  refs(`disputes.json#${d.id}`, d.blocksClaims, 'clm', 'blocksClaims')
}
for (const r of data.retractions) {
  refs(`retractions.json#${r.id}`, r.supersededBy, 'clm', 'supersededBy')
  const subjectPrefix = r.subject.split(':')[0]
  if (!byId[subjectPrefix] || !byId[subjectPrefix].has(r.subject)) {
    fail('C3', `retractions.json#${r.id}`, `subject "${r.subject}" does not resolve`)
  }
  for (const p of r.forbiddenPatterns ?? []) {
    try {
      new RegExp(p.source, p.flags)
    } catch (err) {
      fail('C3', `retractions.json#${r.id}`, `forbiddenPattern is not a valid regex: ${err.message}`)
    }
  }
}
for (const c of data.concepts) {
  refs(`concepts.json#${c.id}`, c.adjacent.map((a) => a.id), 'cpt', 'adjacent[].id')
  if (c.negativeGapId) refs(`concepts.json#${c.id}`, [c.negativeGapId], 'gap', 'negativeGapId')
}
for (const a of data.artifacts) {
  if (a.roleId) refs(`artifacts.json#${a.id}`, [a.roleId], 'rol', 'roleId')
  if (a.access === 'public' && !a.url) {
    fail('C3', `artifacts.json#${a.id}`, 'access is "public" but url is null')
  }
  if (a.access !== 'public' && a.url) {
    fail('C3', `artifacts.json#${a.id}`, `access is "${a.access}" but a url is set — a non-public artifact must not be linked`)
  }
}
for (const r of data.roles) {
  refs(`roles.json#${r.id}`, [r.orgId], 'org', 'orgId')
  refs(`roles.json#${r.id}`, r.advisorIds, 'per', 'advisorIds')
  // `ongoing` means "has not finished", which is compatible with an EXPECTED end
  // date in the future — a degree in progress has both. What it is not compatible
  // with is an end date that has already passed: that is a role the corpus is
  // still describing in the present tense after it stopped.
  if (r.ongoing === true && r.period.end !== null) {
    const [ey, em] = r.period.end.split('-')
    const end = new Date(Number(ey), em ? Number(em) - 1 : 11, 28)
    if (end < new Date()) {
      fail(
        'C3',
        `roles.json#${r.id}`,
        `ongoing is true but period.end (${r.period.end}) is in the past — either the role ended, or the end date is stale`
      )
    }
  }
}
for (const o of data.orgs) {
  if (o.parentOrgId) refs(`orgs.json#${o.id}`, [o.parentOrgId], 'org', 'parentOrgId')
}
for (const p of data.people) refs(`people.json#${p.id}`, [p.orgId], 'org', 'orgId')
for (const profile of data.roleProfiles) {
  for (const req of profile.requirements) {
    const where = `role-profiles.json#${profile.id}/${req.id}`
    refs(where, req.concepts, 'cpt', 'concepts')
    refs(where, req.pinned, 'clm', 'pinned')
    for (const id of req.pinned) {
      const claim = claimById.get(id)
      if (claim && !claim.surfaces.includes('agent')) {
        fail('C3', where, `pinned claim ${id} is not licensed for the "agent" surface, so the scorer can never return it`)
      }
    }
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C4 — in-progress work stays in progress
   ═══════════════════════════════════════════════════════════════════════════ */

/**
 * A completion verb that is NOT negated. The negation window matters: the single
 * most important sentence in this group is "this work is in flight and not
 * shipped", and a rule that forbids the word "shipped" outright would forbid the
 * exact sentence it exists to protect. So the lookbehind lets a negation through
 * and catches the bare assertion.
 */
const NEGATED = /\b(?:not|never|isn't|isn t|is not|aren't|are not|yet to be|rather than|instead of|no)\b[\s\w]{0,24}$/i
const COMPLETION_VERBS = /\b(built|shipped|deployed|delivered|launched|completed|finished)\b/gi

for (const c of data.claims) {
  if (c.status !== 'in-progress') continue
  if (c.tense !== 'present-progressive') {
    fail('C4', `claims.json#${c.id}`, `status is "in-progress" but tense is "${c.tense}"`)
  }
  const outsideQuotes = c.statement.replace(/"[^"]*"/g, ' ')
  let hit = null
  for (const m of outsideQuotes.matchAll(COMPLETION_VERBS)) {
    if (!NEGATED.test(outsideQuotes.slice(0, m.index))) {
      hit = m
      break
    }
  }
  if (hit) {
    fail(
      'C4',
      `claims.json#${c.id}`,
      `statement uses the completion verb "${hit[0]}" outside a quotation. In-progress work must not read as finished — rewrite in the present progressive.`
    )
  }
  if (c.reviewEvery > 180) {
    fail('C4', `claims.json#${c.id}`, `in-progress claims need reviewEvery <= 180 (the tense goes stale fastest); found ${c.reviewEvery}`)
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C5 — a narrative may combine claims; it may not add a fact
   ═══════════════════════════════════════════════════════════════════════════ */

for (const c of data.claims) {
  if (c.kind !== 'narrative') continue
  if (!c.derivedFrom || c.derivedFrom.length === 0) {
    fail('C5', `claims.json#${c.id}`, 'kind is "narrative" with an empty derivedFrom')
    continue
  }
  for (const id of c.derivedFrom) {
    const parent = claimById.get(id)
    if (parent && !parent.asserted) {
      fail('C5', `claims.json#${c.id}`, `derivedFrom includes ${id}, which is not asserted — a narrative may not rest on a claim we decline to make`)
    }
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C6 — every verificationPath resolves
   ═══════════════════════════════════════════════════════════════════════════ */

const REPO_PREFIXES = ['public/', 'backend/', 'data/', 'lib/', 'scripts/', 'app/', 'components/', 'tests/']

/**
 * Resolve an absolute path written inside a human-readable locator.
 *
 * These strings are meant to be read as much as parsed — they carry line
 * references, em-dash commentary, a second path after "and", and filenames with
 * parentheses in them. Rather than impose a machine-friendly format on a field
 * whose whole purpose is to be followed by a person, try the plausible
 * truncations longest-first and accept the first that exists on disk.
 */
function resolveLocalPath(raw) {
  const stripLineRefs = (s) => s.replace(/:[0-9L][-0-9,L\s:]*$/, '').trim()
  let candidate = raw.split(' and /')[0].split(' —')[0].trim()

  // Trim word by word from the right, trying the line-reference-stripped form at
  // each step. This survives filenames containing spaces AND trailing prose,
  // neither of which a single split can handle.
  while (candidate.length > 1) {
    if (candidate.startsWith('/') && existsSync(candidate)) return candidate
    const stripped = stripLineRefs(candidate)
    if (stripped !== candidate && stripped.startsWith('/') && existsSync(stripped)) return stripped
    const cut = candidate.lastIndexOf(' ')
    if (cut <= 0) break
    candidate = candidate.slice(0, cut).trim()
  }
  return null
}

function checkVerificationPath(where, raw) {
  const path = String(raw).trim()

  if (/^https?:\/\//.test(path)) {
    // Format only, never a network call. A gate that depends on the internet is
    // a gate that fails for reasons unrelated to the thing it checks, and a
    // flaky gate gets disabled — which is strictly worse than a warning.
    try {
      new URL(path.split(' ')[0])
    } catch {
      fail('C6', where, `verificationPath looks like a URL but does not parse: ${path.slice(0, 80)}`)
    }
    return
  }

  if (path.startsWith('git show ')) {
    const m = /^git show ([0-9a-f]{7,40}):(\S+)/.exec(path)
    if (!m) fail('C6', where, `git verificationPath must read "git show <ref>:<path>": ${path.slice(0, 80)}`)
    return
  }

  if (path.startsWith('/')) {
    // An owner-archive path: outside both repositories, so CI cannot see it.
    // Warn, never fail — same reasoning as the barn-owl refresh script.
    if (!resolveLocalPath(path)) {
      warn('C6', where, `owner-archive path is not present on this machine: ${path.slice(0, 110)}`)
    }
    return
  }

  if (path.startsWith('sqlite3 ') || path.startsWith('find ') || path.startsWith('git -C ')) {
    return // a reproducible command, checked by running it, not by stat()
  }

  if (REPO_PREFIXES.some((p) => path.startsWith(p))) {
    const file = path.split(':L')[0].split(' —')[0].split(' (')[0].trim()
    if (!existsSync(join(ROOT, file))) {
      fail('C6', where, `repo path does not exist: ${file}`)
    }
    return
  }

  // Anything else is prose (a brief citation, an archive description). Allowed,
  // but it must at least be long enough to be followed by a human.
  if (path.length < 20) {
    fail('C6', where, `verificationPath is neither a path, a URL, a git object nor a followable description: ${JSON.stringify(path)}`)
  }
}

for (const c of data.claims) checkVerificationPath(`claims.json#${c.id}`, c.verificationPath)

for (const s of data.sources) {
  if (s.kind === 'repo-file' && s.repo === 'target') {
    const file = s.locator.startsWith('/') ? s.locator : join(ROOT, s.locator)
    if (!existsSync(file)) fail('C6', `sources.json#${s.id}`, `repo-file locator does not exist: ${s.locator}`)
  }
  if (s.kind === 'owner-archive' && !resolveLocalPath(s.locator)) {
    warn('C6', `sources.json#${s.id}`, `owner-archive locator is not present on this machine: ${s.locator.slice(0, 110)}`)
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C12 — every legacy URL keeps resolving
   ═══════════════════════════════════════════════════════════════════════════ */

for (const a of data.artifacts) {
  if (!a.legacyPath) continue
  if (!existsSync(join(ROOT, a.legacyPath))) {
    fail('C12', `artifacts.json#${a.id}`, `legacyPath does not exist on disk: ${a.legacyPath}. Every path here is a live URL on a résumé domain.`)
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C7 / C10 — surface licensing and mandatory caveats, over hand-authored source
   ═══════════════════════════════════════════════════════════════════════════ */

const SOURCE_DIRS = ['content', 'app', 'components', 'lib']
const SOURCE_EXCLUDE = [join(ROOT, 'lib', 'corpus'), join(ROOT, 'node_modules'), join(ROOT, '.next')]

function walk(dir, exts, exclude = []) {
  const out = []
  if (!existsSync(dir)) return out
  const stack = [dir]
  while (stack.length) {
    const cur = stack.pop()
    if (exclude.some((e) => cur === e || cur.startsWith(e + '/'))) continue
    let entries
    try {
      entries = readdirSync(cur, { withFileTypes: true })
    } catch {
      continue
    }
    for (const e of entries) {
      const p = join(cur, e.name)
      if (e.isDirectory()) stack.push(p)
      else if (e.isFile() && exts.includes(extname(e.name))) out.push(p)
    }
  }
  return out
}

const sourceFiles = SOURCE_DIRS.flatMap((d) =>
  walk(join(ROOT, d), ['.ts', '.tsx', '.js', '.jsx', '.mjs', '.json', '.md'], SOURCE_EXCLUDE)
)

const CLAIM_REF = /\bclm:[a-z0-9]+(?:-[a-z0-9]+)*\b/g
const SURFACE_HINT = /['"](page|resume|jsonld|agent)['"]/

for (const file of sourceFiles) {
  const text = readFileSync(file, 'utf8')
  const rel = relative(ROOT, file)
  const referenced = new Set(text.match(CLAIM_REF) ?? [])
  if (!referenced.size) continue

  // Which surface is this file rendering? Inferred from the directory, with an
  // explicit surface literal in the file as an override. If we cannot tell, we
  // check existence only — a wrong guess would be worse than no guess.
  let surface = null
  if (rel.startsWith('app/resume')) surface = 'resume'
  else if (rel.startsWith('lib/seo')) surface = 'jsonld'
  else if (rel.startsWith('lib/agent')) surface = 'agent'
  else if (rel.startsWith('content') || rel.startsWith('app') || rel.startsWith('components')) surface = 'page'
  const explicit = SURFACE_HINT.exec(text)
  if (explicit) surface = explicit[1]

  for (const id of referenced) {
    const claim = claimById.get(id)
    if (!claim) {
      fail('C7', rel, `references claim "${id}", which does not exist in the corpus`)
      continue
    }
    if (!claim.asserted) {
      fail('C7', rel, `references ${id}, which is asserted:false and must never be rendered`)
      continue
    }
    if (surface && !claim.surfaces.includes(surface)) {
      fail('C7', rel, `references ${id} on surface "${surface}", which it is not licensed for (licensed: ${claim.surfaces.join(', ')})`)
    }
    for (const caveatId of claim.caveats ?? []) {
      if (!referenced.has(caveatId)) {
        fail(
          'C10',
          rel,
          `renders ${id} without its mandatory caveat ${caveatId}. That caveat is not advisory — it is the sentence that keeps the claim from being read as something it is not.`
        )
      }
    }
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C9 — the retraction gate
   ═══════════════════════════════════════════════════════════════════════════ */

const matchers = []
for (const r of data.retractions) {
  for (const phrase of r.forbiddenPhrases) {
    matchers.push({
      id: r.id,
      label: phrase,
      re: new RegExp(phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'i'),
      sayInstead: r.supersededBy ?? [],
    })
  }
  for (const p of r.forbiddenPatterns ?? []) {
    matchers.push({
      id: r.id,
      label: `/${p.source}/`,
      re: new RegExp(p.source, p.flags || 'i'),
      sayInstead: r.supersededBy ?? [],
    })
  }
}

function scanForRetractions(where, text, check = 'C9') {
  for (const m of matchers) {
    const hit = m.re.exec(text)
    if (!hit) continue
    const at = text.indexOf(hit[0])
    const context = text.slice(Math.max(0, at - 50), at + hit[0].length + 50).replace(/\s+/g, ' ')
    fail(
      check,
      where,
      `contains retracted content "${hit[0]}" (${m.id}) — "…${context}…"` +
        (m.sayInstead.length ? ` Say ${m.sayInstead.join(' / ')} instead.` : ' There is no replacement: it does not ship.')
    )
  }
}

// The three corpus fields that are actually SPOKEN to a reader.
for (const g of data.gaps) scanForRetractions(`gaps.json#${g.id}/honestAnswer`, g.honestAnswer)
for (const d of data.disputes) scanForRetractions(`disputes.json#${d.id}/agentGuidance`, d.agentGuidance)
for (const p of data.roleProfiles) {
  for (const req of p.requirements) {
    if (req.fallback) scanForRetractions(`role-profiles.json#${p.id}/${req.id}/fallback`, req.fallback)
  }
}
// And every sentence a claim licenses.
for (const c of data.claims) {
  scanForRetractions(`claims.json#${c.id}/statement`, c.statement)
  scanForRetractions(`claims.json#${c.id}/short`, c.short)
  if (c.value) scanForRetractions(`claims.json#${c.id}/value.display`, c.value.display)
}
// And the hand-authored source that renders them.
for (const file of sourceFiles) {
  scanForRetractions(relative(ROOT, file), readFileSync(file, 'utf8'))
}

