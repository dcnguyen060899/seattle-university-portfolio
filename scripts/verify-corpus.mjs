/* ═══════════════════════════════════════════════════════════════════════════
   C8 / C9 over the built output — only with --built
   ═══════════════════════════════════════════════════════════════════════════ */

const OWNED_IN_PUBLIC_DOCS = ['public/docs/resume_content.html']

function builtHtmlFiles() {
  const roots = [join(ROOT, '.next', 'server', 'app'), join(ROOT, 'out')]
  const files = roots.flatMap((r) => walk(r, ['.html']))
  for (const owned of OWNED_IN_PUBLIC_DOCS) {
    const p = join(ROOT, owned)
    if (existsSync(p)) files.push(p)
  }
  return files
}

/**
 * The one exemption from the numeric gate, and it is deliberately narrow.
 *
 * A generated artifact carries a provenance footer describing the corpus that
 * produced it — how many claims, how many sources, the hash, the date. Those
 * digits are the corpus talking about itself, and they change every time the
 * corpus grows. Requiring each of them to be licensed by a claim would either
 * fail on every edit or push a maintainer into padding the allowlist, and a
 * padded allowlist is the failure mode this whole gate exists to prevent.
 *
 * So the region is marked in the markup, where a reviewer can see it, rather
 * than special-cased by filename where nobody would. Two constraints keep it
 * from becoming a hiding place:
 *   - only C8 skips it; the retraction gate C9 still reads every character
 *   - a file that uses the marker must be a generated file (checked below)
 */
const NO_SCAN = /<!--\s*corpus:no-scan\s*-->[\s\S]*?<!--\s*\/corpus:no-scan\s*-->/g

/** Visible text only: scripts, styles, comments, attributes and JSON-LD removed. */
function visibleText(html, { stripNoScan = false } = {}) {
  return (stripNoScan ? html.replace(NO_SCAN, ' ') : html)
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&[a-z]+;/gi, ' ')
    .replace(/\s+/g, ' ')
}

const NUM = /(?<![\w.])[+-]?\$?\d[\d,]*(?:\.\d+)?%?(?![\w])/g

/** "660,000+", "660K+", "$30.4M", "+20.7%" all normalise to a comparable key. */
function normaliseNumber(tok) {
  let t = String(tok).replace(/[$,+%\s]/g, '').toLowerCase()
  if (/^\d+(\.\d+)?k$/.test(t)) t = String(parseFloat(t) * 1000)
  else if (/^\d+(\.\d+)?m$/.test(t)) t = String(parseFloat(t) * 1000000)
  if (/^\d+\.0+$/.test(t)) t = String(parseFloat(t))
  return t
}

if (BUILT) {
  const files = builtHtmlFiles()
  if (!files.length) {
    warn('C8', '--built', 'found no emitted HTML under .next/server/app or out/. Run the build first, or this pass proves nothing.')
  }

  const licensed = new Set()
  for (const c of data.claims) {
    if (!c.asserted || c.kind !== 'metric') continue
    if (!c.surfaces.includes('page') && !c.surfaces.includes('resume')) continue
    for (const n of c.value.numbers) licensed.add(normaliseNumber(n))
  }
  const allowed = new Set(data.allowedNumbers.map((a) => normaliseNumber(a.value)))

  for (const file of files) {
    const rel = relative(ROOT, file)
    const html = readFileSync(file, 'utf8')

    // C9 reads everything, including any no-scan region: an exemption from the
    // numeric gate is not an exemption from the retraction gate.
    scanForRetractions(rel, visibleText(html))

    if (NO_SCAN.test(html)) {
      NO_SCAN.lastIndex = 0
      if (!html.includes('GENERATED FILE')) {
        fail(
          'C8',
          rel,
          'uses the corpus:no-scan marker but is not a generated file. That marker exempts a region from the numeric gate and exists only for a generator\'s own provenance footer; hand-authored copy may not opt out of the gate.'
        )
      }
    }
    NO_SCAN.lastIndex = 0

    const text = visibleText(html, { stripNoScan: true })

    for (const m of text.matchAll(NUM)) {
      const key = normaliseNumber(m[0])
      if (licensed.has(key) || allowed.has(key)) continue
      const context = text.slice(Math.max(0, m.index - 40), m.index + 40).trim()
      fail(
        'C8',
        rel,
        `renders "${m[0]}", which no claim licenses — "…${context}…". Either add it to the claim's value.numbers with a source, or add it to data/corpus/allowed-non-claim-numbers.json with a reason.`
      )
    }
  }

  // The résumé PDF is the highest-traffic résumé surface on the domain, and it is
  // the one artifact this corpus does not generate. It gets the retraction scan
  // anyway, over its extracted text.
  const pdf = join(ROOT, 'public', 'docs', 'Resume.pdf')
  if (existsSync(pdf)) {
    let text = null
    try {
      const { execFileSync } = await import('node:child_process')
      text = execFileSync('pdftotext', [pdf, '-'], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 })
    } catch {
      warn('C9', 'public/docs/Resume.pdf', 'could not be scanned: `pdftotext` is not on PATH. Install poppler-utils, or the résumé recruiters actually download stays outside the gates.')
    }
    if (text !== null) {
      const before = failures.length
      scanForRetractions('public/docs/Resume.pdf (extracted text)', text)
      if (failures.length > before) {
        // Say what to do, not just what is wrong. This is the one gated artifact
        // the corpus does not yet own, and a failure with no next step is how a
        // gate earns a reputation for crying wolf.
        failures[failures.length - 1].msg +=
          '\n      FIX: `node scripts/gen-resume.mjs --pdf` regenerates this PDF from the corpus via headless Chrome.' +
          '\n      It is not run automatically because overwriting this file changes a byte size the URL harness asserts;' +
          '\n      land the two together. Preview first with `--pdf --pdf-out /tmp/preview.pdf`.'
      }
    }
  } else {
    warn('C9', 'public/docs/Resume.pdf', 'not found; skipping the PDF retraction scan.')
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   C15 — image provenance: where a published picture came from, and what the
   page is allowed to say about it.
   ───────────────────────────────────────────────────────────────────────────
   Every other artifact record points OUTWARD at something a reader can open.
   An artifact with a `provenance` block is different: the site REPRODUCES it.
   Two things can go wrong that no other check would notice.

     1. RIGHTS. The page publishes a work whose origin nobody has stated.
     2. THE UNSTATED CLAIM. A picture is an assertion about what a place looks
        like. An AI-generated image of a real, named campus, published
        unlabelled, is exactly the class of unsourced claim this corpus exists
        to make unreachable — and it would sit in the page's first band, above
        the sentence promising that every claim traces to a source.

   The gate is deliberately asymmetric, because the two failure modes are not
   symmetric:

     · assets on disk + status pending-owner  → WARN, loudly, with the exact
       questions. The owner is allowed to look at the hero before answering
       them; a build that refuses to run would just get the check deleted.
     · status verified + a caption the licence or the disclosure rule requires
       + that caption absent from the built page → FAIL. Once the answer is in,
       shipping the image without the line it obliges is a rights breach, not a
       matter of taste.
     · status blocked + assets still on disk → FAIL. That is the answer coming
       back "no".

   NO ASSETS ON DISK IS A CLEAN PASS. The photograph is progressive enhancement
   over a hero that already works; the absent state is the normal state.
   ═══════════════════════════════════════════════════════════════════════════ */

/** Informational lines printed under PASSED. Declared here because C15 adds to it. */
const orphanReport = []

const IMAGE_EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.gif', '.svg'])

/**
 * Origins that owe the reader a line, as a SET rather than an equality test.
 * `ai-generated-composite` is the hero's actual origin — the owner synthesized
 * one image out of several — and a check written as `origin === 'ai-generated'`
 * would have silently stopped applying the moment that narrower value was
 * recorded. The failure mode of an enum widened past its guard is that the
 * guard passes, which is the worst kind.
 */
const SYNTHETIC_ORIGINS = new Set(['ai-generated', 'ai-generated-composite'])

/**
 * Which files of this artifact are actually on disk right now — the master at
 * any of its declared source paths, plus every image in the generated asset
 * directory. Non-images there (the README that documents the pipeline) are not
 * assets: a directory holding only its own documentation has shipped nothing.
 */
function assetsOnDisk(prov) {
  const found = []
  for (const p of prov.sourcePaths ?? []) {
    if (existsSync(join(ROOT, p))) found.push(p)
  }
  if (prov.assetDir) {
    const dir = join(ROOT, prov.assetDir)
    if (existsSync(dir)) {
      let entries = []
      try {
        entries = readdirSync(dir, { withFileTypes: true })
      } catch {
        entries = []
      }
      for (const e of entries) {
        if (!e.isFile() || e.name.startsWith('.')) continue
        if (!IMAGE_EXTS.has(extname(e.name).toLowerCase())) continue
        found.push(`${prov.assetDir}/${e.name}`)
      }
    }
  }
  return found
}

for (const a of data.artifacts) {
  const prov = a.provenance
  if (!prov) continue
  const where = `artifacts.json#${a.id}/provenance`

  /* — references resolve, and the affiliation is a claim, not an adjective — */

  refs(where, prov.sources, 'src', 'provenance.sources')
  refs(where, [prov.affiliationBasis], 'clm', 'provenance.affiliationBasis')
  const basis = claimById.get(prov.affiliationBasis)
  if (basis && !basis.asserted) {
    fail('C15', where, `affiliationBasis ${prov.affiliationBasis} is asserted:false — the record that bounds what may be implied about the institution cannot itself be one we decline to state`)
  }
  if (basis && !basis.surfaces.includes('page')) {
    fail('C15', where, `affiliationBasis ${prov.affiliationBasis} is not licensed for the "page" surface, so the disclaimer it grounds could never be rendered beside the image`)
  }
  checkVerificationPath(where, prov.verificationPath)

  /* — the status invariants — */

  const needsCaption = prov.captionRule === 'attribution' || prov.captionRule === 'disclosure'

  if (prov.status === 'pending-owner') {
    if (prov.origin !== 'unknown') {
      fail('C15', where, `status is "pending-owner" but origin is "${prov.origin}". An unanswered provenance record states ignorance; it does not carry a best guess.`)
    }
    if (prov.attributionRequired !== null) {
      fail('C15', where, 'status is "pending-owner" but attributionRequired is not null. `false` asserts that no credit is owed — which is precisely the assertion an unanswered record may not make.')
    }
    if (prov.rightsBasis !== null) {
      fail('C15', where, 'status is "pending-owner" but rightsBasis is set. Record the basis only once the owner has stated it.')
    }
    if (prov.captionRule !== 'pending' || prov.captionText !== null) {
      fail('C15', where, `status is "pending-owner", so captionRule must be "pending" and captionText null (found "${prov.captionRule}"). While provenance is open the page says nothing about the image at all.`)
    }
    if (prov.verifiedOn !== null) {
      fail('C15', where, 'status is "pending-owner" but verifiedOn is set — nothing has been verified')
    }
    if (!prov.openQuestions.length) {
      fail('C15', where, 'status is "pending-owner" with no openQuestions. A pending record whose question nobody wrote down never gets closed.')
    }
  }

  if (prov.status === 'verified') {
    if (prov.origin === 'unknown') {
      fail('C15', where, 'status is "verified" but origin is still "unknown"')
    }
    if (!prov.rightsBasis) {
      fail('C15', where, 'status is "verified" with no rightsBasis — say in words what makes publishing this lawful')
    }
    if (typeof prov.attributionRequired !== 'boolean') {
      fail('C15', where, 'status is "verified" but attributionRequired is null — the answer is now known, so record it')
    }
    if (!prov.verifiedOn) {
      fail('C15', where, 'status is "verified" with no verifiedOn date')
    }
    if (prov.captionRule === 'pending') {
      fail('C15', where, 'status is "verified" but captionRule is still "pending" — decide whether the page owes a caption')
    }
    if (SYNTHETIC_ORIGINS.has(prov.origin) && prov.captionRule !== 'disclosure') {
      fail('C15', where, `origin is "${prov.origin}" and captionRule is not "disclosure". A synthetic image of a real, named place published without saying so is an unstated claim, and this page argues that it does not make those.`)
    }
    // The record's own verdict and the rule it implies, checked against each
    // other rather than trusted to agree. Two fields that must not drift is
    // the whole reason both exist.
    if (prov.disclosureRequired === true && prov.captionRule !== 'disclosure') {
      fail('C15', where, `disclosureRequired is true but captionRule is "${prov.captionRule}", so nothing renders. The record contradicts itself.`)
    }
    if (prov.disclosureRequired === false && SYNTHETIC_ORIGINS.has(prov.origin)) {
      fail('C15', where, `origin is "${prov.origin}" but disclosureRequired is false. A synthetic depiction of a real place is exactly the case that owes the reader a line.`)
    }
    if (prov.attributionRequired === true && !needsCaption) {
      fail('C15', where, `attributionRequired is true but captionRule is "${prov.captionRule}" — a required credit has to reach the page as a caption`)
    }
    if (needsCaption && !prov.captionText) {
      fail('C15', where, `captionRule is "${prov.captionRule}" but captionText is null. The line is written here, by a human, in advance — never assembled at render time.`)
    }
  }

  /* — an unresolved record may not be offered as evidence — */

  if (prov.status !== 'verified' && (a.url !== null || a.access === 'public')) {
    fail('C15', `artifacts.json#${a.id}`, `provenance is "${prov.status}", so this artifact must carry url:null and an access other than "public". Rendering the image as decoration is allowed; offering it as something a reader may open and cite is not.`)
  }

  /* — what is actually on disk — */

  const onDisk = assetsOnDisk(prov)

  if (!onDisk.length) {
    orphanReport.push(
      `${a.id}: no image files on disk (checked ${prov.sourcePaths.join(', ')}` +
        (prov.assetDir ? ` and ${prov.assetDir}/` : '') +
        `). The hero falls back to its flat ground, which is the shipped state today.`
    )
    continue
  }

  if (prov.status === 'blocked') {
    fail(
      'C15',
      where,
      `provenance is "blocked" — the image may not ship — but ${onDisk.length} file(s) are still on disk: ${onDisk.join(', ')}. Delete them.`
    )
    continue
  }

  if (prov.status === 'pending-owner') {
    warn(
      'C15',
      where,
      [
        `⚠  ${onDisk.length} image file(s) are on disk while this image's PROVENANCE IS UNANSWERED.`,
        `      Files: ${onDisk.join(', ')}`,
        '',
        '      Previewing is fine. PUBLISHING is not: nobody has stated where this image came from,',
        `      and the page pairs it with an institution's marks. Until ${prov.sources.join(', ')} carries an`,
        '      answer, nothing may be asserted about the picture — no caption, no alt text describing it,',
        '      no claim about what it shows. The accessor (lib/corpus/hero-asset.ts) enforces that at render',
        '      time; this warning exists so the open question is visible on every single build.',
        '',
        '      THE QUESTIONS THE OWNER MUST ANSWER:',
        ...prov.openQuestions.map((q, i) => `        ${i + 1}. ${q}`),
      ].join('\n')
    )
  }

  /* — a required caption must actually reach the page — */

  if (prov.status === 'verified' && needsCaption && prov.captionText) {
    const wanted = prov.captionText.replace(/\s+/g, ' ').trim()
    if (!BUILT) {
      warn(
        'C15',
        where,
        `captionRule is "${prov.captionRule}" and the assets are on disk, but this pass cannot see the rendered page. Run \`node scripts/verify-corpus.mjs --built\` after \`npm run build\` — that is the pass that proves the caption shipped.`
      )
    } else {
      const html = builtHtmlFiles()
      const rendered = html.some((f) =>
        visibleText(readFileSync(f, 'utf8')).replace(/\s+/g, ' ').includes(wanted)
      )
      if (!html.length) {
        warn('C15', where, 'no emitted HTML found, so the caption check proved nothing. Run the build first.')
      } else if (!rendered) {
        fail(
          'C15',
          where,
          `captionRule is "${prov.captionRule}" and the image is on disk, but the required line is not in any built page:\n` +
            `      "${wanted}"\n` +
            '      This is the obligation the provenance answer created. Render it through ' +
            'lib/corpus/hero-asset.ts (heroCaption()) rather than retyping it, so the two cannot drift.'
        )
      }
    }
  }
}

/* ═══════════════════════════════════════════════════════════════════════════
   Orphan report — informational, never a failure
   ═══════════════════════════════════════════════════════════════════════════ */

{
  const carried = new Set(data.claims.flatMap((c) => c.concepts))
  const orphanConcepts = data.concepts.filter((c) => !carried.has(c.id))
  if (orphanConcepts.length) {
    orphanReport.push(
      `concepts carried by no claim: ${orphanConcepts.map((c) => c.id).join(', ')} ` +
        `(intentional when the concept exists only to route a posting's term to a written gap)`
    )
  }
  const gapConcepts = new Set(data.gaps.flatMap((g) => g.concepts))
  const unreachableGaps = data.gaps.filter((g) => g.concepts.length === 0)
  if (unreachableGaps.length) {
    orphanReport.push(
      `gaps reachable only by an explicit topic guard: ${unreachableGaps.map((g) => g.id).join(', ')}`
    )
  }
  void gapConcepts
}

/* ═══════════════════════════════════════════════════════════════════════════
   Write meta.json — hash, counts, timestamp
   ═══════════════════════════════════════════════════════════════════════════ */

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`
  if (value && typeof value === 'object') {
    return `{${Object.keys(value)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${canonical(value[k])}`)
      .join(',')}}`
  }
  return JSON.stringify(value)
}

if (failures.length === 0) {
  const hash = createHash('sha256')
  for (const [key, file] of Object.entries(FILES)) {
    if (key === 'meta') continue
    hash.update(file).update(canonical(data[key]))
  }
  if (snapshot) hash.update('fischer-snapshot.json').update(canonical(snapshot))

  const meta = {
    version: data.meta.version,
    generatedAt: today.toISOString().slice(0, 10),
    corpusHash: `sha256:${hash.digest('hex').slice(0, 32)}`,
    counts: {
      claims: data.claims.length,
      metrics: data.claims.filter((c) => c.kind === 'metric').length,
      caveats: data.claims.filter((c) => c.kind === 'caveat').length,
      narratives: data.claims.filter((c) => c.kind === 'narrative').length,
      sources: data.sources.length,
      roles: data.roles.length,
      artifacts: data.artifacts.length,
      concepts: data.concepts.length,
      skills: data.skills.length,
      gaps: data.gaps.length,
      disputes: data.disputes.length,
      unresolvedDisputes: data.disputes.filter((d) => d.resolution === 'unresolved').length,
      retractions: data.retractions.length,
      roleProfiles: data.roleProfiles.length,
    },
    note: data.meta.note,
  }
  writeFileSync(join(CORPUS, 'meta.json'), JSON.stringify(meta, null, 2) + '\n')
  data.meta = meta
}

/* ═══════════════════════════════════════════════════════════════════════════
   Report
   ═══════════════════════════════════════════════════════════════════════════ */

function report() {
  const mode = BUILT ? 'built output + source' : 'source'
  if (!QUIET) {
    console.log(`\nverify-corpus — scanning ${mode}${STRICT ? ', --strict' : ''}\n`)
  }

  if (failures.length) {
    console.error(`FAILED — ${failures.length} problem(s):\n`)
    const grouped = new Map()
    for (const f of failures) {
      if (!grouped.has(f.check)) grouped.set(f.check, [])
      grouped.get(f.check).push(f)
    }
    for (const [check, list] of [...grouped].sort()) {
      console.error(`  ${check}`)
      for (const f of list) console.error(`    ${f.where}\n      ${f.msg}`)
      console.error('')
    }
  }

  if (warnings.length && !QUIET) {
    console.log(`${warnings.length} warning(s):\n`)
    for (const w of warnings) console.log(`  ${w.check}  ${w.where}\n      ${w.msg}`)
    console.log('')
  }

  if (!failures.length && !QUIET) {
    const c = data.meta?.counts ?? {}
    console.log('PASSED')
    console.log(
      `  ${c.claims} claims (${c.metrics} metric, ${c.caveats} caveat, ${c.narratives} narrative) · ` +
        `${c.sources} sources · ${c.roles} roles · ${c.artifacts} artifacts`
    )
    console.log(
      `  ${c.concepts} concepts · ${c.skills} skills · ${c.gaps} gaps · ` +
        `${c.disputes} disputes (${c.unresolvedDisputes} unresolved) · ${c.retractions} retractions`
    )
    console.log(`  corpusHash ${data.meta.corpusHash}`)
    for (const line of orphanReport) console.log(`  note: ${line}`)
    console.log('')
  }
}

report()

if (failures.length) process.exit(1)
if (STRICT && warnings.length) {
  console.error('--strict: warnings are failures on a release tag.')
  process.exit(1)
}
